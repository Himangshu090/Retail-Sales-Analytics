USE retail_performance_db;

-- ---------- View: one clean table for Excel ----------
-- Joins customers and the (simulated) returns flag onto every order line.
-- LEFT JOINs never drop order rows, so row count must stay 9994.
CREATE OR REPLACE VIEW vw_orders_enriched AS
SELECT
    o.row_id,
    o.order_id,
    o.order_date,
    o.ship_date,
    o.ship_mode,
    o.customer_id,
    c.customer_name,
    c.segment,
    c.country,
    o.city,
    o.state,
    o.postal_code,
    o.region,
    o.product_id,
    o.category,
    o.sub_category,
    o.product_name,
    o.sales,
    o.quantity,
    o.discount,
    o.profit,
    CASE WHEN r.order_id IS NOT NULL THEN 'Yes' ELSE 'No' END AS is_returned
FROM orders o
LEFT JOIN customers c ON o.customer_id = c.customer_id
LEFT JOIN returns   r ON o.order_id    = r.order_id;

-- Checks
SELECT COUNT(*) FROM vw_orders_enriched;                              -- expect 9994
SELECT is_returned, COUNT(*) AS line_items
FROM vw_orders_enriched
GROUP BY is_returned;                                                 -- Yes + No = 9994


-- ---------- 1. Running total of sales by month ----------
-- NOTE: do not alias a column as `year_month`. It is a reserved word
-- in MySQL and causes a syntax error (1064).
-- The aggregation sits in a subquery so the window function runs on
-- plain, already-aggregated values.
SELECT
    sales_month,
    monthly_sales,
    SUM(monthly_sales) OVER (ORDER BY sales_month) AS running_total_sales
FROM (
    SELECT
        DATE_FORMAT(order_date, '%Y-%m') AS sales_month,
        SUM(sales)                        AS monthly_sales
    FROM vw_orders_enriched
    GROUP BY sales_month
) AS monthly_totals
ORDER BY sales_month;
-- Final running_total_sales = 2297200.8603, which matches the raw CSV
-- sum and the Excel Total Sales measure.


-- ---------- 2. Customer cohort analysis ----------
-- Cohort = month of a customer's first order. Shows the lifetime sales
-- generated by each cohort. Use %Y-%m so months sort chronologically.
WITH first_purchase AS (
    SELECT customer_id,
           MIN(DATE_FORMAT(order_date, '%Y-%m')) AS cohort_month
    FROM vw_orders_enriched
    GROUP BY customer_id
)
SELECT
    fp.cohort_month,
    COUNT(DISTINCT o.customer_id) AS customers_in_cohort,
    SUM(o.sales)                  AS lifetime_sales_from_cohort
FROM vw_orders_enriched o
JOIN first_purchase fp ON o.customer_id = fp.customer_id
GROUP BY fp.cohort_month
ORDER BY fp.cohort_month;


-- ---------- 3. Top 3 customers within each region ----------
SELECT *
FROM (
    SELECT
        region,
        customer_name,
        SUM(sales) AS total_sales,
        RANK() OVER (PARTITION BY region ORDER BY SUM(sales) DESC) AS rank_in_region
    FROM vw_orders_enriched
    GROUP BY region, customer_name
) AS ranked
WHERE rank_in_region <= 3;


-- ---------- 4. Sales and margin by category ----------
SELECT
    category,
    ROUND(SUM(sales), 2)                       AS total_sales,
    ROUND(SUM(profit), 2)                      AS total_profit,
    ROUND(SUM(profit) * 100.0 / SUM(sales), 2) AS profit_margin_pct
FROM vw_orders_enriched
GROUP BY category
ORDER BY profit_margin_pct DESC;
-- Furniture: roughly 32% of sales but a margin of about 2.5%.
